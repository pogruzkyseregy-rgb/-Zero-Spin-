package com.zerospin.app.data

/** Следующий свободный id для списка. */
fun nextId(ids: Iterable<Int>): Int = (ids.maxOrNull() ?: 0) + 1

/** Хэш PIN-кода: сам код в памяти телефона не хранится. */
fun hashPin(pin: String): String =
    java.security.MessageDigest.getInstance("SHA-256")
        .digest("zerospin:$pin".toByteArray())
        .joinToString("") { "%02x".format(it) }

/**
 * Ответы «Авроры» в поддержке. Пока это правила по ключевым словам, без сервера.
 * Когда появится бэкенд, сюда подключится запрос к модели.
 */
fun auroraReply(text: String): String {
    val t = text.lowercase()
    if (t.isBlank()) {
        return "Вложение получила 🦊 Пока я понимаю только текст — напишите вопрос словами."
    }
    return when {
        "ник" in t || "имя" in t ->
            "Ник и имя меняются в ПРОФИЛЬ → Редактировать. Ник можно писать без @, он виден другим в круге."
        "статус" in t ->
            "Статус показывается в профиле. Задайте его там же, через Редактировать."
        "рожд" in t || "дата" in t ->
            "Дату рождения укажите в профиле в формате ГГГГ-ММ-ДД, например 1995-03-14."
        "фото" in t || "видео" in t || "файл" in t || "вложен" in t ->
            "Вложения добавляются кнопкой «+ ФАЙЛ» в ленте и в чатах. Можно выбрать сразу несколько файлов."
        "заметк" in t ->
            "Заметки лежат в ПРИЛОЖЕНИЯ → Заметки. Нажмите «+ НОВАЯ», чтобы создать запись."
        "событ" in t ->
            "События — в ПРИЛОЖЕНИЯ → События. Дата в формате ГГГГ-ММ-ДД, время и место необязательны."
        "опрос" in t ->
            "Опросы — в ПРИЛОЖЕНИЯ → Опросы. Варианты добавляются по одному, можно разрешить несколько ответов."
        "перес" in t ->
            "Долгое нажатие на сообщение → Переслать, затем выберите чат. У копии будет пометка, от кого она."
        "избран" in t || "сохран" in t ->
            "Долгое нажатие на сообщение → В избранное. Чат «Избранное» всегда закреплён в списке."
        "закреп" in t ->
            "Сообщение закрепляется через долгое нажатие → Закрепить. Оно появится полоской сверху чата."
        "архив" in t ->
            "Долгое нажатие на чат → В архив. Архив — отдельная вкладка над списком чатов."
        "жирн" in t || "курсив" in t || "формат" in t || "разметк" in t ->
            "Разметка: **жирный**, _курсив_, __подчёркнутый__, ~~зачёркнутый~~ и `код`."
        "исчез" in t || "таймер" in t ->
            "Кнопка ⏱ в шапке чата включает исчезающие сообщения: через час, день или неделю."
        "истори" in t || "момент" in t ->
            "Истории — кружки над лентой. Нажмите «+», выберите фото. Живут сутки."
        "код" in t || "блокир" in t || "pin" in t ->
            "PIN-код на вход ставится в Настройки → Приватность."
        "поиск" in t || "найти" in t ->
            "Поиск по чатам — над списком. Внутри чата — кнопка с лупой в шапке, стрелками ▲▼ листаете совпадения."
        "настро" in t ->
            "Настройки открываются кольцом с ушками в правом верхнем углу экрана."
        "голос" in t || "микрофон" in t ->
            "Голосовое: при пустом поле нажмите 🎙, говорите, затем стрелку — отправить или «Отмена»."
        "привет" in t || "здравств" in t ->
            "Привет! Чем могу помочь?"
        else ->
            "Я отвечаю по теме Zero Spin: профиль, чаты, пересылка, избранное, архив, истории, опросы, PIN-код. Уточните, что нужно."
    }
}
