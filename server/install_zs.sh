for t in aurora admin; do
  cat > /usr/local/bin/zs-$t <<WRAP
#!/bin/sh
# zs-$t: запускается от пользователя aurora, чтобы база оставалась её
export ZS_DB=$DIR/zs.db
if [ "\$(id -u)" = 0 ]; then exec sudo -u aurora -E python3 $DIR/zs_$t.py "\$@"; fi
exec python3 $DIR/zs_$t.py "\$@"
WRAP
  chmod 755 /usr/local/bin/zs-$t
done

echo "[4/6] Ключи"
ENV=/etc/zs-server.env
if [ ! -f "$ENV" ]; then
  cat > "$ENV" <<CONF
RELAY_URL=https://avrora-exe.ru/app-api
PUBLIC_TOKEN=$(openssl rand -hex 24)
