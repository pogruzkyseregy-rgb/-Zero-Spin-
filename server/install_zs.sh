WorkingDirectory=$DIR
EnvironmentFile=$ENV
ExecStart=$DIR/venv/bin/uvicorn zs_server:app --host 127.0.0.1 --port 8077
Restart=always
RestartSec=3
[Install]
WantedBy=multi-user.target
UNIT
